def get_matches():
    """Return all historical matches with normalized team names."""
    normalized = []
    for row in HISTORICAL_MATCHES_RAW:
        year, stage, t1, t2, s1, s2 = row
        normalized.append((year, stage, normalize(t1), normalize(t2), s1, s2))
    return normalized

def get_all_teams():
    """Return set of all teams that have appeared in a WC."""
    matches = get_matches()
    teams = set()
    for _, _, t1, t2, _, _ in matches:
        teams.add(t1)
        teams.add(t2)
    return teams
